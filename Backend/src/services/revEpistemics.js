'use strict';

/**
 * Task 204: Node mirror of the canonical epistemic claim contract
 * (``python/src/intelligence/epistemics.py``, contract rev-claim-v1).
 *
 * Rev is a two-service system: Python reasons and presents the claims, Node
 * orchestrates the boundary. The claim contract must hold at BOTH service
 * boundaries, so Node re-validates every claim it receives with the same
 * stable error codes Python uses. ``validateClaim`` returns a sorted array of
 * error codes; an empty array means the claim is admissible. Any error is
 * fail-closed: the response is rejected, never "cleaned up".
 *
 * Parity with Python is pinned by the golden file
 * ``__tests__/revEpistemics.golden.json`` (generated by
 * ``python/scripts/gen_epistemic_golden.py``): the same claim must produce
 * the same error codes on both runtimes.
 */

const CLAIM_CONTRACT_VERSION = 'rev-claim-v1';

const CLAIM_VERIFIED_FACT = 'verified_fact';
const CLAIM_CALCULATED_OBSERVATION = 'calculated_observation';
const CLAIM_HYPOTHESIS = 'hypothesis';
const CLAIM_UNKNOWN = 'unknown';
const CLAIM_GRADES = [
  CLAIM_VERIFIED_FACT,
  CLAIM_CALCULATED_OBSERVATION,
  CLAIM_HYPOTHESIS,
  CLAIM_UNKNOWN,
];

const UNIT_CURRENCY = 'currency';
const UNIT_RATIO = 'ratio';
const STATUS_AVAILABLE = 'available';

const ROUNDING_MONEY = '2dp_money';
const ROUNDING_PERCENT = '1dp_percent';
const ROUNDING_INTEGER = 'integer_count';

const IMPACT_OBSERVED = 'observed';
const IMPACT_POTENTIAL = 'potential';
const IMPACT_ASSERTED = ['lost', 'recoverable', 'saved', 'prevented', 'avoided', 'leakage'];
const IMPACT_KINDS = [IMPACT_OBSERVED, IMPACT_POTENTIAL, ...IMPACT_ASSERTED];

const MONEY_RE = /^-?\d+(\.\d{1,2})?$/;
const PERCENT_RE = /^-?\d+\.\d$/;

/** Mirror of evidence.normalize_currency: ISO-4217-shaped or null. */
function normalizeCurrency(code) {
  if (typeof code !== 'string') return null;
  const candidate = code.trim().toUpperCase();
  if (candidate.length !== 3 || !/^[A-Z]+$/.test(candidate)) return null;
  return candidate;
}

/**
 * Mirror of epistemics._decimal: a finite number or null. Booleans are never
 * numbers; strings must be plain numeric (the claim pipeline never emits
 * other forms).
 */
function toNumber(value) {
  if (value === null || value === undefined) return null;
  if (typeof value === 'boolean') return null;
  if (typeof value === 'number') return Number.isFinite(value) ? value : null;
  if (typeof value === 'string') {
    const trimmed = value.trim();
    if (!/^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?$/.test(trimmed)) return null;
    const num = Number(trimmed);
    return Number.isFinite(num) ? num : null;
  }
  return null;
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

/**
 * Precision check for a monetary claim value. String values are checked in
 * their raw form (Python validates the decimal string exactly as recorded);
 * numeric values through their canonical string form.
 */
function currencyPrecisionOk(value) {
  if (typeof value === 'string') return MONEY_RE.test(value.trim());
  const num = toNumber(value);
  return num !== null && MONEY_RE.test(String(num));
}

/** Percent check: declared rounding must match the stored figure exactly. */
function percentPrecisionOk(value) {
  if (typeof value === 'string') return PERCENT_RE.test(value.trim());
  const num = toNumber(value);
  return num !== null && PERCENT_RE.test(String(num));
}

function checkFinancialImpact(claim, errors) {
  const impact = claim.financial_impact;
  if (!impact) return;
  if (!IMPACT_KINDS.includes(impact)) {
    errors.add(`unknown_impact_kind:${impact}`);
    return;
  }
  if (IMPACT_ASSERTED.includes(impact)) {
    const calculation = claim.calculation;
    const hasMethod = isPlainObject(calculation)
      && typeof calculation.method === 'string' && calculation.method.trim() !== '';
    if (claim.classification !== CLAIM_CALCULATED_OBSERVATION || !hasMethod) {
      errors.add('asserted_impact_without_method');
    }
  }
}

/**
 * Validate one claim. Returns a sorted array of stable error codes ([] =
 * admissible). Mirrors ``epistemics.validate_claim`` claim-for-claim.
 *
 * ``knownEvidence`` maps evidence id -> item (current items plus comparison
 * items). Claims flagged ``restated`` are follow-up provenance answers: they
 * are validated under the restatement rules (they must name the originating
 * investigation) and are NOT re-derived against this call's evidence.
 */
function validateClaim(claim, knownEvidence, { organizationId = null, storeIds = null } = {}) {
  const errors = new Set();
  if (!isPlainObject(claim)) return ['claim_not_an_object'];
  const grade = claim.classification;
  if (claim.contract_version !== CLAIM_CONTRACT_VERSION) {
    errors.add('unknown_claim_contract_version');
  }
  if (!CLAIM_GRADES.includes(grade)) {
    errors.add('invalid_claim_grade');
    return [...errors].sort();
  }

  const evidenceIds = (claim.evidence_ids || []).filter((id) => typeof id === 'string' && id !== '');
  const restated = claim.restated === true;
  if (restated) {
    if (typeof claim.source_investigation !== 'string' || claim.source_investigation.trim() === '') {
      errors.add('restated_claim_without_source_investigation');
    }
    if (typeof claim.claim_id !== 'string' || !claim.claim_id.startsWith('clm-')) {
      errors.add('restated_claim_without_claim_id');
    }
  } else {
    for (const id of evidenceIds) {
      if (!(id in knownEvidence)) {
        errors.add(`${grade}_cites_unknown_evidence`);
        break;
      }
    }
  }

  if (organizationId && claim.organization_id !== organizationId) {
    errors.add('cross_tenant_claim');
  }
  if (storeIds !== null) {
    const allowed = new Set(storeIds);
    const claimStores = claim.store_ids || [];
    for (const storeId of claimStores) {
      if (!allowed.has(storeId)) {
        errors.add('cross_store_claim');
        break;
      }
    }
  }

  const value = claim.value;
  const unit = claim.unit;
  const currency = normalizeCurrency(claim.currency);

  // Value / precision integrity (established grades only).
  if (grade === CLAIM_VERIFIED_FACT || grade === CLAIM_CALCULATED_OBSERVATION) {
    if (value === null || value === undefined) {
      errors.add('established_claim_without_value');
    } else if (unit === UNIT_CURRENCY) {
      if (currency === null) {
        errors.add('currency_claim_without_currency');
      } else if (toNumber(value) === null) {
        errors.add('currency_claim_not_numeric');
      } else if (!currencyPrecisionOk(value)) {
        errors.add('currency_claim_false_precision');
      } else if (claim.rounding !== ROUNDING_MONEY) {
        errors.add('currency_claim_missing_rounding');
      }
    } else if (unit === 'count') {
      const count = toNumber(value);
      if (count === null || !Number.isInteger(count)) {
        errors.add('count_claim_not_integer');
      } else if (claim.rounding !== ROUNDING_INTEGER && claim.rounding !== null
        && claim.rounding !== undefined) {
        errors.add('count_claim_invalid_rounding');
      }
    } else if (unit === UNIT_RATIO || unit === 'percent') {
      if (toNumber(value) === null) {
        errors.add('percent_claim_not_numeric');
      } else if (claim.rounding === ROUNDING_PERCENT && !percentPrecisionOk(value)) {
        errors.add('percent_claim_false_precision');
      }
    }
  }

  if (grade === CLAIM_VERIFIED_FACT) {
    if (evidenceIds.length === 0) {
      errors.add('verified_fact_without_evidence');
    }
    if (!restated) {
      for (const id of evidenceIds) {
        const item = knownEvidence[id];
        if (!item) {
          errors.add('verified_fact_cites_unknown_evidence');
        } else if (item.status !== STATUS_AVAILABLE && item.status !== 'verified_zero') {
          errors.add('verified_fact_cites_unavailable_evidence');
        } else if (unit === UNIT_CURRENCY && currency !== null
          && normalizeCurrency(item.currency) !== currency) {
          errors.add('verified_fact_currency_mismatch');
        }
      }
    }
    checkFinancialImpact(claim, errors);
  } else if (grade === CLAIM_CALCULATED_OBSERVATION) {
    if (evidenceIds.length === 0) {
      errors.add('calculated_observation_without_evidence');
    }
    const calculation = claim.calculation;
    if (!isPlainObject(calculation)) {
      errors.add('calculated_observation_without_calculation');
    } else {
      if (typeof calculation.formula !== 'string' || calculation.formula.trim() === '') {
        errors.add('calculation_without_formula');
      }
      if (typeof calculation.version !== 'string' || calculation.version.trim() === '') {
        errors.add('calculation_without_version');
      }
      if (typeof calculation.rounding !== 'string' || calculation.rounding.trim() === '') {
        errors.add('calculation_without_rounding');
      }
      const calcInputs = Array.isArray(calculation.inputs) ? calculation.inputs : [];
      if (calcInputs.length === 0) {
        errors.add('calculation_without_inputs');
      }
      const inputCurrencies = new Set();
      for (const entry of calcInputs) {
        const evidenceId = entry && entry.evidence_id;
        if (!evidenceId) {
          errors.add('calculation_input_without_evidence');
          continue;
        }
        if (!restated && !(evidenceId in knownEvidence)) {
          errors.add('calculation_input_cites_unknown_evidence');
        }
        const entryValue = entry ? entry.value : undefined;
        if (entryValue === null || entryValue === undefined) {
          errors.add('calculation_input_missing_value');
        } else {
          const entryCurrency = normalizeCurrency(entry ? entry.currency : null);
          if (entryCurrency) inputCurrencies.add(entryCurrency);
        }
      }
      if (inputCurrencies.size > 1) {
        errors.add('calculation_mixes_currencies');
      }
      const method = typeof calculation.method === 'string' ? calculation.method : '';
      if (method === 'percent_change' || method === 'ratio') {
        for (const entry of calcInputs) {
          if (!entry || (entry.role !== 'previous' && entry.role !== 'denominator')) continue;
          const den = toNumber(entry.value);
          if (entry.value === null || entry.value === undefined || den === null || den <= 0) {
            errors.add('calculation_zero_or_missing_denominator');
            break;
          }
        }
      }
    }
    checkFinancialImpact(claim, errors);
  } else if (grade === CLAIM_HYPOTHESIS) {
    const hypothesis = claim.hypothesis;
    if (!isPlainObject(hypothesis)) {
      errors.add('hypothesis_without_block');
    } else {
      if (hypothesis.verified === true) {
        errors.add('hypothesis_claimed_verified');
      }
      const missing = (hypothesis.missing_evidence || [])
        .filter((text) => typeof text === 'string' && text.trim() !== '');
      if (missing.length === 0) {
        errors.add('hypothesis_without_missing_evidence');
      }
    }
    if (claim.financial_impact) {
      errors.add('hypothesis_carries_financial_impact');
    }
  } else if (grade === CLAIM_UNKNOWN) {
    if (value !== null && value !== undefined) {
      errors.add('unknown_claim_carries_value');
    }
    const unknown = claim.unknown;
    if (!isPlainObject(unknown)) {
      errors.add('unknown_without_block');
    } else if (typeof unknown.reason !== 'string' || unknown.reason.trim() === '') {
      errors.add('unknown_without_reason');
    }
  }

  return [...errors].sort();
}

/** Validate a set of claims against the evidence that exists. */
function validateClaims(claims, items, options = {}) {
  const known = {};
  for (const item of items || []) {
    if (item && typeof item.id === 'string' && item.id !== '') known[item.id] = item;
  }
  const errors = new Set();
  for (const claim of claims || []) {
    if (!isPlainObject(claim)) {
      errors.add('claim_not_an_object');
      continue;
    }
    for (const code of validateClaim(claim, known, options)) errors.add(code);
  }
  return [...errors].sort();
}

/**
 * Descriptive rollup of a claim set: counts by grade plus the epistemic
 * posture per metric. Mirrors ``epistemics.epistemic_rollup``; never upgrades
 * a grade.
 */
function epistemicRollup(claims) {
  const counts = {};
  for (const grade of CLAIM_GRADES) counts[grade] = 0;
  const perMetric = {};
  for (const claim of claims || []) {
    if (!isPlainObject(claim)) continue;
    const grade = claim.classification;
    if (grade in counts) counts[grade] += 1;
    if (claim.metric) {
      if (!perMetric[claim.metric]) perMetric[claim.metric] = new Set();
      perMetric[claim.metric].add(grade);
    }
  }
  const metrics = {};
  for (const metric of Object.keys(perMetric).sort()) {
    metrics[metric] = [...perMetric[metric]].sort();
  }
  return {
    contract_version: CLAIM_CONTRACT_VERSION,
    counts,
    total: Object.values(counts).reduce((sum, n) => sum + n, 0),
    metrics,
  };
}

module.exports = {
  CLAIM_CONTRACT_VERSION,
  CLAIM_GRADES,
  IMPACT_ASSERTED,
  IMPACT_KINDS,
  normalizeCurrency,
  validateClaim,
  validateClaims,
  epistemicRollup,
};
